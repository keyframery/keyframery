test("motion profile, cut and easing radios support keyboard selection and one tab stop", async ({ page }) => {
  await page.goto("/theme")
  const profiles = page.getByRole("radiogroup", { name: "Motion profile", exact: true })
  await expect(profiles.locator('[tabindex="0"]')).toHaveCount(1)
  const expressive = profiles.getByRole("radio", { name: "Expressive", exact: true })
  await expressive.focus()
  await expressive.press("ArrowRight")
  const quiet = profiles.getByRole("radio", { name: "Quiet", exact: true })
  await expect(quiet).toBeFocused()
  await expect(quiet).toHaveAttribute("aria-checked", "true")
  await quiet.press("End")
  await expect(expressive).toBeFocused()
  await expect(expressive).toHaveAttribute("aria-checked", "true")
  await expressive.press("Home")
  await expect(quiet).toBeFocused()
  await quiet.press("ArrowDown")
  const crisp = profiles.getByRole("radio", { name: "Crisp", exact: true })
  await expect(crisp).toBeFocused()
  await expect(crisp).toHaveAttribute("aria-checked", "true")
  await expect(profiles.locator('[tabindex="0"]')).toHaveCount(1)

  const dialogCuts = page.getByRole("radiogroup", { name: "Dialog, alert dialog, command", exact: true })
  const punch = dialogCuts.getByRole("radio", { name: "punch-in", exact: true })
  await punch.focus()
  await punch.press("ArrowUp")
  const rack = dialogCuts.getByRole("radio", { name: "rack-focus", exact: true })
  await expect(rack).toBeFocused()
  await expect(rack).toHaveAttribute("aria-checked", "true")
  await expect(page.getByTestId("theme-jsx")).not.toContainText('dialog="punch-in"')
  await rack.press("ArrowLeft")
  const none = dialogCuts.getByRole("radio", { name: "none", exact: true })
  await expect(none).toBeFocused()
  await expect(none).toHaveAttribute("aria-checked", "true")
  await expect(dialogCuts.locator('[tabindex="0"]')).toHaveCount(1)

  const eases = page.getByRole("radiogroup", { name: "Easing in", exact: true })
  const snappy = eases.getByRole("radio", { name: "Snappy", exact: true })
  await snappy.focus()
  await snappy.press("ArrowRight")
  const gentle = eases.getByRole("radio", { name: "Gentle", exact: true })
  await expect(gentle).toBeFocused()
  await expect(gentle).toHaveAttribute("aria-checked", "true")
  await expect(page.getByTestId("theme-css")).toContainText("cubic-bezier(0.4, 0, 0.2, 1)")
  await expect(eases.locator('[tabindex="0"]')).toHaveCount(1)
})
