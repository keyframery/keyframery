/* Every <style href="kf-…"> block in src/components/{primitives,ui} (the core-built components have
   them too, and they are not in frameworks/classes): its content is a string, a template without
   substitutions, or a const in the same file holding one (or a + of them). */
function sourceStyles() {
  const ts = require("typescript")
  const out = new Map()
  for (const dir of ["primitives", "ui"]) {
    const base = path.join(root, "src/components", dir)
    for (const f of fs.readdirSync(base).filter((f) => f.endsWith(".tsx"))) {
      const text = fs.readFileSync(path.join(base, f), "utf8")
      if (!text.includes("<style")) continue
      const sf = ts.createSourceFile(f, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
      const consts = new Map()
      const visitConsts = (n) => {
        if (ts.isVariableDeclaration(n) && ts.isIdentifier(n.name) && n.initializer) consts.set(n.name.text, n.initializer)
        ts.forEachChild(n, visitConsts)
      }
      visitConsts(sf)
      const value = (e) => {
        if (!e) return undefined
        if (ts.isStringLiteral(e) || ts.isNoSubstitutionTemplateLiteral(e)) return e.text
        if (ts.isParenthesizedExpression(e) || ts.isAsExpression(e)) return value(e.expression)
        if (ts.isIdentifier(e)) return value(consts.get(e.text))
        if (ts.isBinaryExpression(e) && e.operatorToken.kind === ts.SyntaxKind.PlusToken) {
          const a = value(e.left), b = value(e.right)
          return a === undefined || b === undefined ? undefined : a + b
        }
        /* [ "…", "…" ].join("") */
        if (ts.isCallExpression(e) && ts.isPropertyAccessExpression(e.expression) && e.expression.name.text === "join" && ts.isArrayLiteralExpression(e.expression.expression)) {
          const sep = e.arguments.length ? value(e.arguments[0]) : ","
          const items = e.expression.expression.elements.map(value)
          return sep === undefined || items.some((x) => x === undefined) ? undefined : items.join(sep)
        }
        if (ts.isTemplateExpression(e)) {
          let s = e.head.text
          for (const span of e.templateSpans) {
            const v = value(span.expression)
            if (v === undefined) return undefined
            s += v + span.literal.text
          }
          return s
        }
        return undefined
      }
      const visit = (n) => {
        if (ts.isJsxElement(n) && n.openingElement.tagName.getText() === "style") {
          const href = n.openingElement.attributes.properties.find((a) => ts.isJsxAttribute(a) && a.name.getText() === "href")
          const hrefText = href?.initializer && ts.isStringLiteral(href.initializer) ? href.initializer.text : undefined
          const expr = n.children.find((c) => ts.isJsxExpression(c))?.expression
          let css = value(expr)
          /* Built with a little code (table: Array.from(…).join("")): evaluate our own source. */
          if (css === undefined && expr && ts.isIdentifier(expr) && consts.has(expr.text)) {
            try {
              const v = new Function(`return (${consts.get(expr.text).getText()})`)()
              if (typeof v === "string") css = v
            } catch {}
          }
          if (hrefText && css !== undefined && !out.has(hrefText)) out.set(hrefText, css)
          else if (hrefText && css === undefined) out.set(hrefText, { unread: `${dir}/${f}` })
        }
        ts.forEachChild(n, visit)
      }
      visit(sf)
    }
  }
  return out
}

/* Every <style href> block the React components define (href -> css), from the extraction and the sources. */
function styleBlocks(datas) {
  const seen = new Map()
  for (const d of datas) for (const [href, css] of Object.entries(d.styles)) if (!seen.has(href)) seen.set(href, css)
  for (const [href, css] of sourceStyles()) if (!seen.has(href) && typeof css === "string") seen.set(href, css)
  return seen
}

/* Vue: the blocks a generated component needs, shipped inside it (a non-scoped <style> in its root SFC), the
   way React's <style href="kf-…"> lives inside the component: a user's project has only the motion tokens in
   its CSS, not frameworks/vue/_lib/keyframery.css. A block is needed when React's files for the slug render it,
   or when the component's own SFCs name one of its keyframes or registered properties (a select popup's
   kf-cascade). Duplicates across components are harmless. */
function vueStyleFor(d, sfcTexts, blocks) {
  const text = sfcTexts.join("\n")
  const named = (name) => new RegExp(`(?<![A-Za-z0-9-])${name.replace(/[-]/g, "\\-")}(?![A-Za-z0-9-])`).test(text)
  const hrefs = []
  for (const [href, css] of blocks) {
    if (typeof css !== "string") continue
    const names = [...css.matchAll(/@keyframes\s+([\w-]+)|@property\s+(--[\w-]+)/g)].map((m) => m[1] ?? m[2])
    if (href in (d.styles ?? {}) || names.some(named)) hrefs.push(href)
  }
  if (!hrefs.length) return ""
  return `\n<style>\n/* The keyframes and registered properties this component uses (React: <style href="…"> in the component). */\n${hrefs.map((h) => `/* ${h} */\n${blocks.get(h).trim()}`).join("\n")}\n</style>\n`
}

function allStyles(datas) {
  const seen = new Map()
  for (const d of datas) for (const [href, css] of Object.entries(d.styles)) if (!seen.has(href)) seen.set(href, css)
  for (const [href, css] of sourceStyles()) {
    if (seen.has(href)) continue
    if (typeof css === "string") seen.set(href, css)
    else console.warn(`keyframery.css: could not read <style href="${href}"> in ${css.unread}`)
  }
  return [...seen].map(([href, css]) => `/* ${href} */\n${css}`).join("\n")
}

