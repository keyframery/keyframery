/* ---------- web components: one compiled stylesheet ---------- */

function cssEscape(s) {
  /* CSS.escape for class names. */
  let out = ""
  for (let i = 0; i < s.length; i++) {
    const ch = s[i]
    const code = s.charCodeAt(i)
    if (i === 0 && /[0-9]/.test(ch)) out += `\\${code.toString(16)} `
    else if (/[a-zA-Z0-9_-]/.test(ch) || code >= 0x80) out += ch
    else out += "\\" + ch
  }
  return out
}

async function webCss(datas) {
  const { compile } = await import("tailwindcss")
  const twDir = path.dirname(require.resolve("tailwindcss/package.json"))
  /* Which slots use each class, and which slots carry each group/peer marker. */
  const users = new Map()
  /* Some components reuse another's parts (color-picker uses popover-trigger, menubar uses menu-item).
     A stylesheet matches by data-slot alone, so each slot takes the classes of the component it is
     named after; the others' differences are reported, not merged. */
  const owners = new Map()
  for (const d of datas)
    for (const slot of Object.keys(d.slots)) {
      const cur = owners.get(slot)
      const fits = (slug) => slot === slug || slot.startsWith(slug + "-")
      if (!cur || (fits(d.slug) && (!fits(cur) || d.slug.length > cur.length))) owners.set(slot, d.slug)
    }
  const shared = []
  for (const d of datas)
    for (const [slot, cls] of Object.entries(d.slots)) {
      if (owners.get(slot) !== d.slug) {
        const own = datas.find((x) => x.slug === owners.get(slot)).slots[slot]
        if (own !== cls) shared.push({ slot, component: d.slug, styledAs: owners.get(slot) })
        continue
      }
      const vpart = Object.values(d.parts).find((p) => p.root?.slot === slot && Object.keys(p.variants ?? {}).length)
      if (vpart) {
        /* A part with a variant prop: React sets data-variant, so each variant gets its own rule and
           the default applies only without one. */
        const [, info] = Object.entries(vpart.variants)[0]
        const add = (key, c) => c.split(/\s+/).filter(Boolean).forEach((x) => (users.get(x) ?? users.set(x, new Set()).get(x)).add(key))
        add(`v:${slot}:${info.default}`, cls)
        for (const [value, tree] of Object.entries(info.values)) {
          const root = tree.find((n) => n.receivesProps) ?? tree[0]
          if (root?.class) add(`v:${slot}:${value}`, root.class)
        }
        continue
      }
      for (const c of cls.split(/\s+/).filter(Boolean)) (users.get(c) ?? users.set(c, new Set()).get(c)).add(slot)
    }
  const defaults = new Map()
  for (const d of datas) for (const p of Object.values(d.parts)) for (const [, info] of Object.entries(p.variants ?? {})) if (p.root?.slot) defaults.set(p.root.slot, info.default)
  /* Elements the React parts add of their own (chevrons, checks, the switch thumb's default) have no
     data-slot. In the web stylesheet they are matched by data-kf="<name>"; the snippets show the markup. */
  const snippets = webSnippets(datas)
  for (const [kf, cls] of snippets.classes)
    for (const c of cls.split(/\s+/).filter(Boolean)) (users.get(c) ?? users.set(c, new Set()).get(c)).add(`kf:${kf}`)

  const input = `
@import "tailwindcss/theme.css" layer(theme);
@import "tailwindcss/utilities.css" layer(utilities);
${motionTokensCss()}
`
  const compiler = await compile(input, {
    base: root,
    loadStylesheet: async (id, base) => {
      const file = id.startsWith("tailwindcss/") ? path.join(twDir, id.slice("tailwindcss/".length)) : path.resolve(base, id)
      return { path: file, base: path.dirname(file), content: fs.readFileSync(file, "utf8") }
    },
  })
  let css = compiler.build([...users.keys()])

  const sel = (slots) => {
    const one = (s) => {
      if (s.startsWith("kf:")) return `[data-kf="${s.slice(3)}"]`
      if (s.startsWith("v:")) {
        const [, slot, value] = s.split(":")
        return value === defaults.get(slot) ? `[data-slot="${slot}"]:is(:not([data-variant]), [data-variant="${value}"])` : `[data-slot="${slot}"][data-variant="${value}"]`
      }
      return `[data-slot="${s}"]`
    }
    const list = [...slots].sort().map(one)
    /* Every rewritten class must keep a class's specificity (0,1,0), or utility order stops deciding.
       :is() takes the highest specificity in its list, so groups and variant selectors go in :where()
       and get exactly one attribute selector back. */
    if (list.length === 1 && !list[0].includes(":is(") && !list[0].includes("][")) return list[0]
    const hasSlot = list.some((x) => x.startsWith("[data-slot"))
    const hasKf = list.some((x) => x.startsWith("[data-kf"))
    return `:where(${list.join(", ")})${hasSlot && hasKf ? ":is([data-slot], [data-kf])" : hasKf ? "[data-kf]" : "[data-slot]"}`
  }
  /* Longest names first, so `.group` never eats `.group\/key`. */
  const names = [...users.keys()].sort((a, b) => b.length - a.length)
  const unused = []
  for (const name of names) {
    const esc = cssEscape(name)
    const re = new RegExp("\\." + esc.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "(?![\\w\\\\-])", "g")
    if (!re.test(css)) {
      unused.push(name)
      continue
    }
    css = css.replace(re, sel(users.get(name)))
  }
  /* Markers: `group/x` and `peer/x` emit no rule; variants refer to them as `.group\/x`. */
  css = css.replace(/\.(group|peer)(\\\/[\w-]+)?(?![\w\\-])/g, (m) => {
    const name = m.slice(1).replace(/\\\//g, "/")
    const owners = users.get(name)
    return owners ? sel(owners) : m
  })
  /* data-ready (set by the React primitive 150ms after mount) becomes "not the first placement",
     which UI SDK reports as data-activation-direction="none". */
  css = css.replace(/\[data-ready\]/g, ':not([data-activation-direction="none"])')

  const { transform } = require(require.resolve("lightningcss", { paths: [path.join(root, "node_modules/.pnpm/node_modules")] }))
  const flat = transform({
    filename: "keyframery.css",
    code: Buffer.from(css),
    minify: false,
    targets: { chrome: 111 << 16, safari: (16 << 16) | (4 << 8), firefox: 128 << 16 },
  }).code.toString()

  const reset = `/* A zero-specificity reset for UI SDK parts, the part of Tailwind's preflight the classes rely on.
   Your own CSS still wins over it. */
@layer base {
  :where([data-slot]), :where([data-slot])::before, :where([data-slot])::after { box-sizing: border-box; border: 0 solid; margin: 0; padding: 0; }
  :where(button[data-slot], input[data-slot], textarea[data-slot], select[data-slot], [data-slot] button, [data-slot] input) { font: inherit; letter-spacing: inherit; color: inherit; background-color: transparent; border-radius: 0; }
  :where([data-slot][popover], dialog[data-slot]) { color: inherit; background-color: transparent; }
  :where([data-slot]) :where(svg) { display: block; vertical-align: middle; }
  :where([data-slot]) :where(h1, h2, h3, h4, h5, h6, p) { margin: 0; font-size: inherit; font-weight: inherit; }
}`
  const out = `/* ${banner}
   Keyframery for UI SDK web components (@ui-sdk/web): one stylesheet. Link it and every <ui-*> part
   gets the Keyframery look and motion, matched by its data-slot. Set data-motion="springy" (or calm,
   snappy, playful) on <html> to change the motion style; subtle is the default. Add class="dark" on
   <html> for the dark theme. Elements the React components add of their own (chevrons, check marks,
   copies of tab labels) are not added by a stylesheet: see frameworks/classes/_summary.json. */
@layer theme, base, components, utilities;

${reset}

${flat}
/* Keyframes and registered properties the components inject in React (<style href="kf-…">). */
${allStyles(datas)}
`
  return { css: out, unused, snippets: snippets.html, shared }
}

/* For each component, the markup of every exported part as <ui-*> elements, with data-kf on the
   elements a stylesheet cannot add. Parts whose behaviour sits on a native element (a trigger's
   button) show that element inside. */
const wrappedButtonParts = /-(trigger|close|tab|clear)$/
function webSnippets(datas) {
  const classes = new Map()
  const html = new Map()
  for (const d of datas) {
    const out = []
    for (const part of Object.values(d.parts)) {
      if (!part.tree.length) continue
      let n = 0
      const name = (node) => `${kebab(part.export)}-${node.tag}${n++ ? n : ""}`
      const render = (nodes, depth) =>
        nodes
          .map((node) => {
            const pad = "  ".repeat(depth)
            if (node.t === "text") return pad + node.value
            if (node.t === "slot") return node.fallback?.length ? render(node.fallback, depth) : `${pad}<!-- your content -->`
            if (node.t === "if") return render(node.else, depth)
            if (node.t === "stateFn") return render(node.children, depth)
            if (node.t === "part") {
              const tag = `ui-${node.slot}`
              const pattrs = Object.entries(node.attrs ?? {})
                .filter(([k, v]) => typeof v !== "object" && !/^aria-|^data-/.test(k))
                .map(([k, v]) => (v === true ? ` ${kebab(k)}` : ` ${kebab(k)}="${attrEsc(v)}"`))
                .join("")
              const inner = render(node.children, depth + (wrappedButtonParts.test(node.slot) ? 2 : 1))
              if (wrappedButtonParts.test(node.slot)) return `${pad}<${tag}${pattrs}>\n${pad}  <button type="button">\n${inner}\n${pad}  </button>\n${pad}</${tag}>`
              return inner.trim() ? `${pad}<${tag}${pattrs}>\n${inner}\n${pad}</${tag}>` : `${pad}<${tag}${pattrs}></${tag}>`
            }
            const attrs = Object.entries(node.attrs ?? {})
              .filter(([, v]) => typeof v !== "object")
              .map(([k, v]) => ` ${domAttr(k)}="${attrEsc(v)}"`)
              .join("")
            let kf = ""
            if (!node.attrs?.["data-slot"] && node.class) {
              const id = name(node)
              classes.set(id, node.class)
              kf = ` data-kf="${id}"`
            }
            const inner = render(node.children ?? [], depth + 1)
            return inner.trim() ? `${pad}<${node.tag}${kf}${attrs}>\n${inner}\n${pad}</${node.tag}>` : `${pad}<${node.tag}${kf}${attrs}></${node.tag}>`
          })
          .join("\n")
      out.push(`<!-- ${part.export} -->\n${render(part.tree, 0)}`)
    }
    html.set(d.slug, out.join("\n\n"))
  }
  return { classes, html }
}

/* ---------- main ---------- */

function write(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, text)
}

const utilsTs = `/* ${banner} */
import { twMerge } from "tailwind-merge"

type ClassValue = string | number | null | undefined | false | ClassValue[] | Record<string, unknown>

function flatten(value: ClassValue, out: string[]) {
  if (!value) return
  if (typeof value === "string" || typeof value === "number") out.push(String(value))
  else if (Array.isArray(value)) for (const v of value) flatten(v, out)
  else for (const [k, v] of Object.entries(value)) if (v) out.push(k)
}

/* clsx + tailwind-merge, like shadcn's cn. */
export function cn(...inputs: ClassValue[]) {
  const out: string[] = []
  flatten(inputs, out)
  return twMerge(out.join(" "))
}
`

const solidUtilsTs = `${utilsTs}
/* UI SDK for Solid accepts a class or a function of the part's state; keep both working. */
export function withClass<S>(base: string | undefined, theirs: unknown): any {
  return typeof theirs === "function" ? (state: S) => cn(base, (theirs as (s: S) => string | undefined)(state)) : cn(base, theirs as string)
}

/* The user's content: plain, or a function of the part's state. */
export function content<S>(children: unknown, state: S, fallback: unknown): any {
  if (children === undefined || children === null) return typeof fallback === "function" ? fallback() : fallback
  return typeof children === "function" ? (children as (s: S) => unknown)(state) : children
}
`

async function main() {
  const args = process.argv.slice(2)
  if (args[0] === "--nodes") {
    const d = JSON.parse(fs.readFileSync(path.join(classesDir, args[1] + ".json"), "utf8"))
    const parts = args[3] === "orig" ? d.original : d.parts
    classedNodes(parts[args[2]].tree).forEach((n, i) => console.log(i, n.t === "part" ? n.name : `<${n.tag}>`, n.class.slice(0, 100)))
    return
  }
  /* With slugs: only those Vue components (and the shared Vue lib) are written; svelte/solid/web are left as they
     are. A slug with no frameworks/classes/<slug>.json (the core-built ones) is copied from its override.
     With no slug: everything, every framework. */
  const all = fs.readdirSync(classesDir).filter((f) => f.endsWith(".json") && !f.startsWith("_")).map((f) => f.slice(0, -5))
  const slugs = args.length ? args.filter((s) => all.includes(s)) : all
  const datas = slugs.map((s) => JSON.parse(fs.readFileSync(path.join(classesDir, s + ".json"), "utf8")))
  const unextracted = args.filter((s) => !all.includes(s))

  /* Vue. For each component:
       frameworks/overrides/vue/<slug>/ exists  -> copied as it is to frameworks/vue/<slug>/ (hand-written
                                                    by the component's builder; nothing is generated)
       otherwise                                -> one SFC per part, from the extracted tree, or from
                                                    scripts/frameworks/vue-parts/<slug>/<Part>.vue when
                                                    that hand template exists (any other .vue there,
                                                    e.g. SelectItems, is added and exported too)
     Overrides for components with no extracted classes (the core-built ones, context-menu, motion-style)
     are copied as well. Every core file src/components/core/<name>.ts is copied to
     frameworks/vue/core/<name>-core.ts (its install path components/keyframery/core/<name>-core.ts),
     with its @/components/core/<x> imports rewritten to @/components/keyframery/core/<x>-core.
     frameworks/vue/_lib/ = scripts/frameworks/vue-parts/_lib/* + keyframery.css (installs as lib/). */
  const overridesDir = path.join(fw, "overrides/vue")
  const overridden = new Set(fs.existsSync(overridesDir) ? fs.readdirSync(overridesDir).filter((f) => fs.statSync(path.join(overridesDir, f)).isDirectory()) : [])
  const vueReport = { generated: [], hand: [], overridden: [] }
  let blocksCache = null
  for (const d of datas) {
    const vueDir = path.join(fw, "vue", d.slug)
    fs.rmSync(vueDir, { recursive: true, force: true })
    if (overridden.has(d.slug)) {
      fs.cpSync(path.join(overridesDir, d.slug), vueDir, { recursive: true })
      vueReport.overridden.push(d.slug)
      continue
    }
    const handDir = path.join(vuePartsDir, d.slug)
    const hand = new Set(fs.existsSync(handDir) ? fs.readdirSync(handDir).filter((f) => f.endsWith(".vue")).map((f) => f.slice(0, -4)) : [])
    const vueIndex = [`/* ${banner} */`, `export * from "${sdkModule(d.module, "vue")}"`]
    const names = new Set([...Object.values(d.parts).filter((p) => p.tree.length || hand.has(p.export)).map((p) => p.export), ...hand])
    for (const name of [...names].sort()) {
      const p = d.parts[name]
      let out
      if (hand.has(name)) {
        out = vueHandPart(d, path.join(handDir, `${name}.vue`))
        write(path.join(vueDir, `${name}.vue`), out)
        vueReport.hand.push(`${d.slug}/${name}`)
      } else {
        out = vuePart(d.slug, p)
        /* A patch: small edits on the generated SFC (a conditional the extraction drops). */
        const patch = path.join(handDir, `${name}.patch.mjs`)
        if (fs.existsSync(patch)) {
          out = (await import(pathToFileURL(patch).href)).default(out, { replace: replaceOnce, cls: (spec) => JSON.stringify(classRef(d, spec)), constant: (spec) => JSON.stringify(constRef(spec)) })
          vueReport.hand.push(`${d.slug}/${name} (patch)`)
        }
        out = pruneUnused(out)
        write(path.join(vueDir, `${name}.vue`), out)
      }
      vueIndex.push(`export { default as ${name} } from "./${name}.vue"`)
      if (new RegExp(`^export type ${name}Props\\b`, "m").test(out)) vueIndex.push(`export type { ${name}Props } from "./${name}.vue"`)
    }
    /* The component's keyframes, in its root SFC (the part named like the component, else the first). */
    const files = fs.readdirSync(vueDir).filter((f) => f.endsWith(".vue")).sort()
    const rootFile = files.find((f) => kebab(f.slice(0, -4)) === d.slug) ?? files[0]
    blocksCache ??= styleBlocks(fs.readdirSync(classesDir).filter((f) => f.endsWith(".json") && !f.startsWith("_")).map((f) => JSON.parse(fs.readFileSync(path.join(classesDir, f), "utf8"))))
    let style = rootFile ? vueStyleFor(d, files.map((f) => fs.readFileSync(path.join(vueDir, f), "utf8")), blocksCache) : ""
    /* scripts/frameworks/vue-parts/<slug>/style.css: CSS of our own for a UI SDK Vue difference (drawer RTL). */
    const ownCss = path.join(handDir, "style.css")
    if (rootFile && fs.existsSync(ownCss)) {
      const css = fs.readFileSync(ownCss, "utf8").trim()
      style = style ? style.replace(/\n<\/style>\n$/, `\n${css}\n</style>\n`) : `\n<style>\n${css}\n</style>\n`
    }
    if (style) fs.appendFileSync(path.join(vueDir, rootFile), style)
    const extraIndex = path.join(handDir, "index.ts")
    if (fs.existsSync(extraIndex)) vueIndex.push(fs.readFileSync(extraIndex, "utf8").trim())
    write(path.join(vueDir, "index.ts"), vueIndex.join("\n") + "\n")
    vueReport.generated.push(d.slug)
  }
  for (const slug of args.length ? unextracted : overridden) {
      if (datas.some((d) => d.slug === slug)) continue
      if (!overridden.has(slug)) {
        console.error(`vue: ${slug}: no frameworks/classes/${slug}.json and no frameworks/overrides/vue/${slug}/, skipped`)
        process.exitCode = 1
        continue
      }
      const vueDir = path.join(fw, "vue", slug)
      fs.rmSync(vueDir, { recursive: true, force: true })
      fs.cpSync(path.join(overridesDir, slug), vueDir, { recursive: true })
      vueReport.overridden.push(slug)
    }
  const coreSrc = path.join(root, "src/components/core")
  const coreOut = path.join(fw, "vue/core")
  fs.rmSync(coreOut, { recursive: true, force: true })
  for (const f of fs.readdirSync(coreSrc).filter((f) => f.endsWith(".ts"))) {
    const text = fs.readFileSync(path.join(coreSrc, f), "utf8").replace(/(["'])@\/components\/core\/([\w-]+)\1/g, (_, q, name) => `${q}@/components/keyframery/core/${name}-core${q}`)
    write(path.join(coreOut, f.replace(/\.ts$/, "-core.ts")), text)
  }
  fs.rmSync(path.join(fw, "vue/_lib"), { recursive: true, force: true })
  fs.cpSync(path.join(vuePartsDir, "_lib"), path.join(fw, "vue/_lib"), { recursive: true })
  fs.rmSync(path.join(fw, "vue/lib"), { recursive: true, force: true })
  fs.rmSync(path.join(fw, "vue/keyframery.css"), { force: true })
  /* Vue's lib CSS: the tokens and the five motion styles only (what a user's project has, React's motion.json).
     Every component carries its own keyframes and registered properties in a <style> block. */
  write(path.join(fw, "vue/_lib/keyframery.css"), vueTokensCss())
  if (args.length) {
    console.log(`vue: ${vueReport.generated.length} generated (${vueReport.hand.length} hand-template parts), ${vueReport.overridden.length} copied from overrides${vueReport.overridden.length ? ": " + vueReport.overridden.join(" ") : ""} (svelte, solid, web untouched: run with no slug for those)`)
    return
  }

  for (const d of datas) {
    const svDir = path.join(fw, "svelte", d.slug)
    fs.rmSync(svDir, { recursive: true, force: true })
    const svIndex = [`/* ${banner} */`, `export * from "${sdkModule(d.module, "svelte")}"`]
    for (const p of Object.values(d.parts).filter((p) => p.tree.length)) {
      write(path.join(svDir, `${kebab(p.export)}.svelte`), sveltePart(d.slug, p))
      svIndex.push(`export { default as ${p.export} } from "./${kebab(p.export)}.svelte"`)
    }
    write(path.join(svDir, "index.ts"), svIndex.join("\n") + "\n")

    write(path.join(fw, "solid", `${d.slug}.tsx`), solidComponent(d.slug, d))
  }

  /* Shared files. The CSS covers every extracted component, not only the ones generated now. */
  const every = fs.readdirSync(classesDir).filter((f) => f.endsWith(".json") && !f.startsWith("_")).map((f) => JSON.parse(fs.readFileSync(path.join(classesDir, f), "utf8")))
  write(path.join(fw, "svelte/lib/utils.ts"), utilsTs)
  write(path.join(fw, "solid/lib/utils.ts"), solidUtilsTs)
  const twCss = tailwindCss(every)
  for (const f of ["svelte", "solid"]) write(path.join(fw, f, "keyframery.css"), twCss)
  const web = await webCss(every)
  write(path.join(fw, "web/keyframery.css"), web.css)
  write(path.join(fw, "web/shared-slots.json"), JSON.stringify(web.shared, null, 2) + "\n")
  for (const [slug, html] of web.snippets) write(path.join(fw, "web/snippets", `${slug}.html`), `<!-- ${banner}\n     Markup for the ${slug} parts as <ui-*> elements. Elements with data-kf are ones the React parts add\n     themselves; keep them so keyframery.css can style them. -->\n\n${html}\n`)
  console.log(`generated ${datas.length} components for vue, svelte, solid; web/keyframery.css ${(web.css.length / 1024).toFixed(0)} KB`)
  console.log(`vue: ${vueReport.generated.length} generated (${vueReport.hand.length} hand-template parts), ${vueReport.overridden.length} copied from overrides${vueReport.overridden.length ? ": " + vueReport.overridden.join(" ") : ""}`)
  if (web.unused.length) console.log(`classes Tailwind emitted nothing for (${web.unused.length}): ${web.unused.slice(0, 40).join(" ")}`)
}

main()
